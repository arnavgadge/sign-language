"""
dashboard/window.py
-----------------------
Window lifecycle for the technical dashboard, using the same OpenCV
window mechanism already used elsewhere in main.py (e.g. the existing
'M'-key debug window) — no new UI framework introduced.

Critical distinction from that existing debug window: THIS window's
CONTENT is only regenerated by `update()`, which the caller must invoke
solely on a genuine new recognized-word event. `show()` — called every
render loop iteration while visible, same as the existing debug window's
pattern — just re-blits the already-rendered canvas; it performs no
engine computation and does not even touch the trace object.
"""
import cv2

from resolution.models import EngineTrace
from .renderer import render_dashboard, blank_placeholder


class EngineDashboard:
    """
    Usage
    -----
    dashboard = EngineDashboard()

    # On a genuine accepted-word resolution (NOT every frame):
    dashboard.update(intent_engine.last_trace, intent_engine.store.get_history(user_id))

    # Every render loop iteration, only while toggled on:
    if dashboard.visible:
        dashboard.show()

    # On keypress toggle:
    dashboard.toggle()
    """

    def __init__(self, window_name: str = "AE-CP | Engine Dashboard"):
        self.window_name = window_name
        self.visible = False
        self._canvas = blank_placeholder()
        self._update_count = 0   # observability: how many real updates have happened

    def update(self, trace: EngineTrace, history_rows: list) -> None:
        """Regenerate the cached canvas from a REAL EngineTrace. Call this
        ONLY when a word was actually just resolved — never per-frame."""
        if trace is None:
            return
        self._canvas = render_dashboard(trace, history_rows)
        self._update_count += 1

    def show(self) -> None:
        """Cheap redisplay of the cached canvas. Safe to call every frame
        while `visible` — does not recompute or touch engine state."""
        cv2.imshow(self.window_name, self._canvas)

    def toggle(self) -> bool:
        self.visible = not self.visible
        if not self.visible:
            cv2.destroyWindow(self.window_name)
        return self.visible

    def close(self) -> None:
        if self.visible:
            cv2.destroyWindow(self.window_name)
        self.visible = False
